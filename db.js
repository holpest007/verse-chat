// ============================================================================
//  db.js — выбор хранилища данных.
//  Пытаемся использовать встроенный SQLite (node:sqlite, нужен Node 22+).
//  Если он недоступен (старая версия Node или файловая система только для чтения) —
//  автоматически переключаемся на хранение В ПАМЯТИ, чтобы сервер не падал и
//  чат/группы/онлайн продолжали работать (без сохранения между перезапусками).
// ============================================================================

let api;
try {
  api = require('./db-sqlite');
  console.log('[db] Хранилище: SQLite (data.db)');
} catch (e) {
  console.warn('[db] SQLite недоступен, работаем в памяти. Причина:', e.message);
  api = require('./db-memory');
}

module.exports = api;
